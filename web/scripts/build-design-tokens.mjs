import fs from 'node:fs';
const tokens = JSON.parse(
  fs.readFileSync(new URL('../design-system/tokens.json', import.meta.url), 'utf8'),
);
const declarations = () =>
  Object.entries(tokens.colors)
    .map(([name, value]) => `  --color-${name}: ${value};`)
    .join('\n');
const output = `/* Generated by scripts/build-design-tokens.mjs. Edit design-system/tokens.json. */\n@theme {\n  --font-sans: '${tokens.font}', system-ui, sans-serif;\n${declarations()}\n}\n:root {\n  color-scheme: only light;\n${Object.entries(
  tokens.motion,
)
  .map(([k, v]) => `  --motion-${k}: ${v}ms;`)
  .join(
    '\n',
  )}\n  --ease-ui: cubic-bezier(0.2, 0.8, 0.2, 1);\n  --sidebar-width: ${tokens.layout.sidebar}px;\n  --sidebar-collapsed-width: ${tokens.layout.sidebarCollapsed}px;\n  --content-max: ${tokens.layout.contentMax}px;\n}\n`;
const dimensions = [
  ...tokens.spacing.map((v) => `  --space-${v}: ${v}px;`),
  ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(tokens.type).map(([k, v]) => `  --type-${k}: ${v / 16}rem;`),
  `  --toolbar-height: ${tokens.layout.toolbar}px;`,
].join('\n');
const editions = Object.entries(tokens.editions)
  .map(([edition, theme]) => {
    const values = [
      ...Object.entries(theme.colors).map(([k, v]) => `  --color-${k}: ${v};`),
      ...Object.entries(theme.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
      ...Object.entries(theme.shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
    ];
    return `.portal-${edition} {\n${values.join('\n')}\n}\n`;
  })
  .join('');
const completeOutput = output.replace(/\n}\n$/, `\n${dimensions}\n}\n`) + editions;
const target = new URL('../src/app/styles/tokens.css', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== completeOutput) {
    console.error('Design tokens are out of sync. Run node scripts/build-design-tokens.mjs.');
    process.exitCode = 1;
  }
} else fs.writeFileSync(target, completeOutput);

// Exported single-color UI vectors follow the same semantic palette. Brand logos are excluded.
const iconRoles = {
  b3e82: 'brand',
  '6116d': 'brand',
  '5bebb': 'brand',
  '5eb5d': 'brand',
  '8b38a': 'brand',
  b4407: 'brand',
  '0975b': 'brand',
  '1f3a3': 'brand',
  '3d858': 'brand',
  '992b3': 'action',
  '77a90': 'action',
  '4b9be': 'action',
  '00c80': 'action',
  '24c2f': 'action',
  67146: 'selected',
  '0c7ed': 'warning',
  '5fce4': 'success',
};
for (const [name, role] of Object.entries(iconRoles)) {
  const asset = new URL(`../src/shared/assets/figma-v2/${name}.svg`, import.meta.url);
  const current = fs.readFileSync(asset, 'utf8');
  const expected = current.replace(/#[\da-f]{6}/gi, tokens.colors[role].toUpperCase());
  if (current === expected) continue;
  if (process.argv.includes('--check')) {
    console.error(`Icon color is out of sync: ${name}.svg. Run npm run tokens:build.`);
    process.exitCode = 1;
  } else fs.writeFileSync(asset, expected);
}
